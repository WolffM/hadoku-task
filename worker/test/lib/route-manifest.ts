/**
 * Derive route-manifest.ts from the live route groups.
 *
 * Shared by the generator (`pnpm run gen:worker`) and route-manifest-verify.ts,
 * so the file and its drift check cannot disagree about what a row is.
 */
import { OpenAPIHono } from '@hono/zod-openapi'
import { ROUTE_GROUPS, ROOT_SERVED, type RouteGroup } from '../../src/route-groups'
import type { AppContext } from '../../src/types'

export type ManifestRow = readonly [method: string, path: string, group: RouteGroup]

export async function collectRouteManifest(): Promise<ManifestRow[]> {
  const rows: ManifestRow[] = []
  const seen = new Set<string>()
  for (const group of Object.keys(ROUTE_GROUPS) as RouteGroup[]) {
    // Mount it exactly as root's group shell does, so `path` is Hono's own merge
    // of the prefix (a group's '/' becomes '/task/api', not '/task/api/').
    const mounted = new OpenAPIHono<AppContext>().route('/task/api', await ROUTE_GROUPS[group]())
    for (const { method, path } of mounted.routes) {
      // An ALL row is group middleware. Merged onto one app it ran for EVERY
      // group's routes under the prefix; behind a lazy shell it would only run
      // for its own. That changes behaviour, so it needs a decision, not a row.
      if (method === 'ALL') {
        throw new Error(
          `group "${group}" registers middleware (${method} ${path}); route groups must not — put it on root or on the routes`
        )
      }
      const key = `${method} ${path}`
      // Each openapi() route contributes two rows (validator, handler).
      if (seen.has(`${key} ${group}`) || ROOT_SERVED.has(key)) continue
      seen.add(`${key} ${group}`)
      rows.push([method, path, group])
    }
  }
  return rows
}

export function renderManifest(rows: ManifestRow[]): string {
  const body = rows.map(r => `  ${JSON.stringify(r)},`).join('\n')
  return `/**
 * GENERATED by \`pnpm run gen:worker\` from each route group's live routes — do
 * not edit by hand. route-manifest-verify.ts fails when this drifts from them.
 *
 * Root registers one stub per row, in this order, that loads the row's group and
 * forwards the request. Several groups serve paths under /task/api/boards/…, so a
 * group cannot be picked by prefix; this table is what lets root route a request
 * without building any group's schemas. Row order is match precedence.
 */
import type { RouteGroup } from './route-groups'

export const ROUTE_MANIFEST: ReadonlyArray<
  readonly [method: string, path: string, group: RouteGroup]
> = [
${body}
]
`
}
